def split_and_balance(data):
    class_data = {i: [] for i in range(len(classes))}
    for path, label in data:
        class_data[label].append((path, label))
    max_len = max(len(v) for v in class_data.values())

    balanced = []
    for label, items in class_data.items():
        items = items.copy()
        if len(items) < max_len:
            items += random.choices(items, k=max_len - len(items))
        balanced.extend(items)

    random.shuffle(balanced)
    total = len(balanced)
    train_len = int(0.7 * total)
    val_len = int(0.1 * total)

    train = balanced[:train_len]
    val = balanced[train_len:train_len + val_len]
    test = balanced[train_len + val_len:]
    return train, val, test

